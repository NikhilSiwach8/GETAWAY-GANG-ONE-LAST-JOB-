"""Build docs/RTP_REPORT.md from measured data only.

Inputs:
  * a stratified_sim.py JSON report (independent Monte Carlo of the reel model), and
  * optionally the published lookup table + weighting info written by run.py (the actual game the
    RGS serves), whose statistics are computed exactly from the weights.

Usage: python math/tools/make_report.py math/reports/calibration_run_v1.json [library_dir]
"""

import csv
import json
import math
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
WINCAP = 12000


def pct(x, d=3):
    return f"{x * 100:.{d}f}%"


def one_in(p):
    return "never observed" if p <= 0 else f"1 in {1 / p:,.0f}"


def lut_stats(library):
    lut = os.path.join(library, "publish_files", "lookUpTable_base_0.csv")
    seg = os.path.join(library, "lookup_tables", "lookUpTableSegmented_base.csv")
    crit = {}
    with open(seg, encoding="UTF-8") as f:
        for book_id, c, base, free in csv.reader(f):
            crit[int(book_id)] = (c, float(base), float(free))
    rows = []
    with open(lut, encoding="UTF-8") as f:
        for book_id, w, pay in csv.reader(f):
            rows.append((int(book_id), int(w), int(pay) / 100))
    tw = sum(w for _, w, _ in rows)
    mean = sum(w * p for _, w, p in rows) / tw
    m2 = sum(w * p * p for _, w, p in rows) / tw
    out = {
        "books": len(rows),
        "nonzero_payouts": len({p for _, w, p in rows if p > 0 and w > 0}),
        "rtp": mean,
        "sd": math.sqrt(m2 - mean * mean),
        "hit_rate": sum(w for _, w, p in rows if p > 0) / tw,
        "max_win": max(p for _, w, p in rows if w > 0),
        "p_maxwin": sum(w for _, w, p in rows if p >= WINCAP) / tw,
        "maxwin_books": sum(1 for _, w, p in rows if p >= WINCAP),
    }
    by = {}
    for i, w, p in rows:
        c, base, free = crit[i]
        d = by.setdefault(c, {"w": 0, "rtp": 0.0, "base": 0.0, "free": 0.0, "n": 0})
        d["w"] += w
        d["n"] += 1
        d["rtp"] += w * p
        d["base"] += w * base
        d["free"] += w * free
    out["strata"] = {c: {"probability": d["w"] / tw, "rtp": d["rtp"] / tw, "books": d["n"]} for c, d in by.items()}
    out["base_game_rtp"] = sum(d["base"] for d in by.values()) / tw
    out["free_game_rtp"] = sum(d["free"] for d in by.values()) / tw
    edges = [0, 0.1, 1, 2, 5, 10, 20, 50, 100, 250, 500, 1000, 2500, 5000, 12000, 1e12]
    hist = []
    for lo, hi in zip(edges, edges[1:]):
        p = sum(w for _, w, x in rows if lo <= x < hi) / tw
        hist.append((lo, hi, p))
    out["hist"] = hist
    weighting = os.path.join(library, "lut_weighting_base.json")
    if os.path.exists(weighting):
        out["weighting"] = json.load(open(weighting, encoding="UTF-8"))
    return out


def main():
    sim = json.load(open(sys.argv[1], encoding="UTF-8"))
    library = sys.argv[2] if len(sys.argv) > 2 else None
    L = []
    w = L.append
    w("# GETAWAY GANG: ONE LAST JOB! — RTP & Volatility Report\n")
    w("Every number below is generated by `math/tools/make_report.py` from measured data. Nothing is typed by hand.\n")

    if library and os.path.exists(os.path.join(library, "publish_files", "lookUpTable_base_0.csv")):
        s = lut_stats(library)
        w("## 1. Published game (lookup table served by the RGS)\n")
        w("The RGS picks each round's outcome by weight from `lookUpTable_base_0.csv`, so the table *is* the game. "
          "These statistics are **exact** for the published game, computed from the integer weights.\n")
        w("| Metric | Value |\n|---|---|")
        w(f"| Books (simulations) | {s['books']:,} |")
        w(f"| Distinct non-zero payouts | {s['nonzero_payouts']:,} |")
        w(f"| **RTP** | **{pct(s['rtp'], 4)}** |")
        w(f"| Base-game wins share of RTP | {pct(s['base_game_rtp'])} |")
        w(f"| Free-game wins share of RTP | {pct(s['free_game_rtp'])} |")
        w(f"| Hit rate (round pays > 0) | {pct(s['hit_rate'], 2)} ({one_in(s['hit_rate'])}) |")
        w(f"| Standard deviation (x bet) | {s['sd']:.2f} |")
        w(f"| Maximum win in table | {s['max_win']:,.2f}x |")
        w(f"| P(max win {WINCAP:,}x) | {one_in(s['p_maxwin'])} ({s['maxwin_books']} books) |")
        if "weighting" in s:
            wt = s["weighting"]
            w(f"| Natural RTP of the book sample (before trim) | {pct(wt['natural_rtp_of_book_sample'], 4)} |")
            w(f"| Zero-win re-weighting factor (RTP trim) | x{wt['zero_win_trim_factor']:.5f} |")
        w("")
        w("| Stratum | Books | Probability | RTP contribution |\n|---|---:|---:|---:|")
        for c, d in sorted(s["strata"].items()):
            w(f"| {c} | {d['books']:,} | {one_in(d['probability'])} | {pct(d['rtp'])} |")
        w("\n**Win distribution (probability per round):**\n")
        w("| Win range (x bet) | Probability |\n|---|---:|")
        for lo, hi, p in s["hist"]:
            label = f"{lo:g} – {hi:g}" if hi < 1e12 else f"{lo:g} (max win)"
            w(f"| {label} | {p * 100:.5f}% |")
        w("")

    w("## 2. Independent Monte Carlo of the reel model\n")
    w("`math/tools/stratified_sim.py` runs the real SDK `GameState.run_spin` with seeds that do not overlap the "
      "book generation. RTP is decomposed exactly by the initial-board Scatter count:\n")
    w("`RTP = P(<3 S)·E[win | base] + P(3 S)·E[win | Heist] + P(4+ S)·E[win | Escape]`\n")
    w("The trigger probabilities come from the reel strips analytically. The conditional means are measured.\n")
    pr = sim["probabilities"]
    w("| Quantity | Value |\n|---|---|")
    w(f"| **Estimated RTP** | **{pct(sim['rtp'], 3)}** ± {pct(1.96 * sim['rtp_se'], 3)} (95% CI {pct(sim['rtp_95ci'][0])} – {pct(sim['rtp_95ci'][1])}) |")
    w(f"| THE HEIST trigger | {one_in(pr['heist'])} spins (exact) |")
    w(f"| THE PERFECT ESCAPE trigger | {one_in(pr['escape'])} spins (exact) |")
    w(f"| Runtime | {sim['seconds'] / 60:.1f} min |")
    w("")
    w("**RTP contributions vs. the initial budget**\n")
    w("| Component | Budget | Measured |\n|---|---:|---:|")
    c = sim["contributions"]
    w(f"| Ordinary base-game wins (no crew, no re-spin) | 30.00% | {pct(c.get('ordinary_base', 0))} |")
    w(f"| Base-game Crew Chaos (crew reveals + Chaos Re-spins) | 12.00% | {pct(c.get('crew_base', 0))} |")
    w(f"| THE HEIST (free-spin wins) | 31.00% | {pct(c.get('heist', 0))} |")
    w(f"| THE PERFECT ESCAPE (free-spin wins incl. Final Escape) | 23.00% | {pct(c.get('escape', 0))} |")
    w(f"| …of which Final Escape awards | – | {pct(c.get('final_escape', 0))} |")
    w("")
    w("Each round's win is credited to exactly one bucket: the base reveal it came from, or the bonus it was won in. So no payout is counted twice.\n")
    w("**Per-stratum measurements**\n")
    w("| Stratum | Sims | Mean win | SD | Hit rate | Max | 12,000x rounds | Rounds with crew |\n|---|---:|---:|---:|---:|---:|---:|---:|")
    for name, s2 in sim["strata"].items():
        w(f"| {name} | {s2['sims']:,} | {s2['mean_win']:.3f}x | {s2['sd']:.2f} | {pct(s2['hit_rate'], 2)} | "
          f"{s2['max_win']:,.1f}x | {s2['cap_hits']} | {pct(s2['rounds_with_crew'], 2)} |")
    w("")
    if "basegame" in sim["strata"]:
        b = sim["strata"]["basegame"]["per_round"]
        n_b = sim["strata"]["basegame"]["sims"]
        w("**Base-game feature frequencies (per paid spin, non-trigger rounds)**\n")
        w("| Event | Frequency |\n|---|---:|")
        for k in ("act_R", "act_B", "act_T", "act_F"):
            w(f"| {dict(act_R='Roxy', act_B='Byte', act_T='Tank', act_F='Fuse')[k]} activation | {one_in(b.get(k, 0))} |")
        for k in sorted(x for x in b if x.startswith("combo_")):
            w(f"| Combo {k[6:]} | {one_in(b[k])} |")
        w(f"| Perfectly Bad Plan | {one_in(b.get('pbp', 0))} |")
        hist = sim["strata"]["basegame"]["histogram"]
        for k in sorted(x for x in hist if x.startswith("chain_")):
            w(f"| Chaos Re-spin chain length {k[6:]} | {hist[k] / n_b * 100:.4f}% |")
        w("")
    for bonus in ("heist", "escape"):
        if bonus in sim["strata"]:
            st = sim["strata"][bonus]
            pr2 = st["per_round"]
            w(f"**{bonus.upper()} feature counts (average per bonus round)**\n")
            w("| Event | Average per round |\n|---|---:|")
            for k in sorted(pr2):
                if k.startswith(("act_", "combo_")) or k in ("pbp", "activations"):
                    w(f"| {k} | {pr2[k]:.3f} |")
            w("")
            w(f"Win distribution for {bonus} rounds (share of rounds):\n")
            w("| Range | Share |\n|---|---:|")
            for k, v in sorted(st["histogram"].items(), key=lambda kv: float(kv[0].strip("[").split(",")[0]) if kv[0].startswith("[") else 1e18):
                if not k.startswith("chain_"):
                    w(f"| {k} | {v / st['sims'] * 100:.4f}% |")
            w("")
    out = os.path.join(ROOT, "docs", "RTP_REPORT.md")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="UTF-8") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
