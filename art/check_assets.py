"""Check delivered art/audio against the asset list in art/asset_prompts.py.

Drop files into art/delivery/ named by asset ID (any sub-folders are fine), e.g.
  art/delivery/symbols/SYM-H1.png
  art/delivery/symbols/SYM-H1-ANIM.json + SYM-H1-ANIM.atlas + SYM-H1-ANIM.png
  art/delivery/music/MUS-MAIN.ogg
Then run:  python3 art/check_assets.py        (writes art/delivery/STATUS.md)
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import asset_prompts as ap  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "delivery")
IMAGE = {".png", ".webp"}
VIDEO = {".webm", ".mp4"}
AUDIO = {".ogg", ".m4a", ".wav", ".mp3"}

# What counts as "delivered" per asset kind, and the expected image size (w, h) if any.
RULES = {
    "symbol": ("image", (512, 512), True),
    "symbol_anim": ("anim", None, True),
    "char_sheet": ("image", None, False),
    "char_anim": ("anim", None, True),
    "bg": ("image", (3840, 2160), False),
    "bg_loop": ("anim", None, False),
    "fx": ("anim", None, True),
    "cinematic": ("anim", None, False),
    "ui": ("image", None, True),
    "screen": ("image_or_anim", None, False),
    "music": ("audio", None, False),
    "sfx": ("audio", None, False),
    "vo": ("audio", None, False),
}

# Priority tiers: what to make first for the biggest visible improvement.
TIER1 = [a for a in ap.ASSETS if a[3] == "symbol"] + [
    a for a in ap.ASSETS if a[1] in {"BG-MAIN", "BG-HEIST", "BG-ESCAPE", "UI-LOGO", "UI-REEL-FRAME", "UI-REEL-BG"}
]
TIER2 = [a for a in ap.ASSETS if a[3] in {"symbol_anim", "fx", "ui"} or a[1].endswith("-POSE") or a[1].startswith("ANIM-") and a[1].endswith("-IDLE")]
TIER2 = [a for a in TIER2 if a not in TIER1]


def tier(asset):
    if asset in TIER1:
        return 1
    if asset in TIER2:
        return 2
    return 3


def index_files():
    """Map each file to the longest asset ID it is named after (ID or ID-variant)."""
    ids = sorted({a[1].upper() for a in ap.ASSETS}, key=len, reverse=True)
    found, unmatched = {}, []
    for dirpath, _, files in os.walk(ROOT):
        for f in files:
            stem = os.path.splitext(f)[0].upper()
            if stem in ("README", "STATUS"):
                continue
            match = next((i for i in ids if stem == i or stem.startswith(i + "-")), None)
            if match:
                found.setdefault(match, []).append(os.path.join(dirpath, f))
            else:
                unmatched.append(f)
    return found, unmatched


def image_info(path):
    try:
        from PIL import Image
    except ImportError:
        return None
    with Image.open(path) as im:
        has_alpha = im.mode in ("RGBA", "LA") or (im.mode == "P" and "transparency" in im.info)
        return im.size, has_alpha


def check(asset, files):
    _, aid, _, kind, _ = asset
    need, size, alpha = RULES[kind]
    exts = {os.path.splitext(p)[1].lower() for p in files}
    problems = []
    images = [p for p in files if os.path.splitext(p)[1].lower() in IMAGE]
    is_spine = ".json" in exts and ".atlas" in exts
    ok = {
        "image": bool(images),
        "anim": is_spine or bool(exts & VIDEO) or bool(images),
        "image_or_anim": bool(images) or is_spine or bool(exts & VIDEO),
        "audio": bool(exts & AUDIO),
    }[need]
    if not ok:
        problems.append(f"expected {need} file, got {sorted(exts)}")
    if need == "anim" and images and not (is_spine or exts & VIDEO):
        problems.append("only still images: expected Spine (.json + .atlas) or a video/sequence")
    for p in images if need in ("image", "image_or_anim") else []:
        info = image_info(p)
        if info is None:
            continue
        (w, h), has_alpha = info
        if size and (w, h) != size and (w, h) != (size[0] // 2, size[1] // 2):
            problems.append(f"{os.path.basename(p)} is {w}x{h}, expected {size[0]}x{size[1]}")
        if alpha and not has_alpha:
            problems.append(f"{os.path.basename(p)} has no transparency")
    return problems


def main():
    found, unknown = index_files()
    lines = ["# Asset delivery status", "", "Generated by `python3 art/check_assets.py`.", ""]
    totals = {1: [0, 0], 2: [0, 0], 3: [0, 0]}
    rows = []
    for asset in ap.ASSETS:
        sec, aid, title, kind, _ = asset
        t = tier(asset)
        totals[t][1] += 1
        files = found.get(aid.upper(), [])
        if not files:
            rows.append((t, sec, aid, title, "⬜ missing", ""))
            continue
        problems = check(asset, files)
        if problems:
            rows.append((t, sec, aid, title, "⚠️ needs fixing", "; ".join(problems)))
        else:
            totals[t][0] += 1
            rows.append((t, sec, aid, title, "✅ delivered", ", ".join(os.path.basename(p) for p in files)))
    unknown = sorted(unknown)
    lines.append("| Priority | Delivered |\n|---|---|")
    for t, label in ((1, "Tier 1 — make first"), (2, "Tier 2"), (3, "Tier 3")):
        lines.append(f"| {label} | {totals[t][0]} / {totals[t][1]} |")
    lines.append("")
    if unknown:
        lines.append("**Files not matching any asset ID** (rename to the ID): " + ", ".join(unknown) + "\n")
    lines.append("| Tier | Asset ID | Asset | Status | Notes |\n|---|---|---|---|---|")
    for t, sec, aid, title, status, note in sorted(rows, key=lambda r: (r[0], r[2])):
        lines.append(f"| {t} | {aid} | {title} | {status} | {note} |")
    with open(os.path.join(ROOT, "STATUS.md"), "w", encoding="UTF-8") as f:
        f.write("\n".join(lines) + "\n")
    for t in (1, 2, 3):
        print(f"tier {t}: {totals[t][0]}/{totals[t][1]} delivered")
    if unknown:
        print("unmatched files:", ", ".join(unknown))
    print("wrote art/delivery/STATUS.md")


if __name__ == "__main__":
    main()
