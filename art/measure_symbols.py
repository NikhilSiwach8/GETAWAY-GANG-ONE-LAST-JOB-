"""Measure the in-game symbol textures and write frontend/getaway_gang/src/game/symbols/symbolMetrics.ts.

The shared symbol renderer uses these numbers to present the approved art as one collection without
editing a pixel: optical size and centring, where the contact shadow sits, and where idle glints catch the
light. Re-run after any symbol art is replaced:

    python3 art/measure_symbols.py

Per symbol (all values are fractions of the 512 px canvas):
  body      bbox of the solid body (alpha > 0.5 after a 9 px erosion, so thin baked sparkle rays are ignored)
  coverage  share of the canvas covered by the body
  glint     centroid of the brightest 1.5 % of body pixels (the art's own specular highlight)
  clipped   share of body pixels with a channel at 255 (blown highlights)
  fit       {scale, dx, dy}: optical normalisation applied at render time (see FAMILY_TARGETS)
"""
import json
import os

import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
GG = os.path.join(ROOT, "frontend", "getaway_gang", "static", "assets", "gg")
OUT = os.path.join(ROOT, "frontend", "getaway_gang", "src", "game", "symbols", "symbolMetrics.ts")

FAMILY = {
    "H1": "high", "H2": "high", "H3": "high", "H4": "high",
    "L1": "royal", "L2": "royal", "L3": "royal", "L4": "royal",
    "WILD": "special", "SCATTER": "special",
    "ROXY": "crew", "BYTE": "crew", "TANK": "crew", "FUSE": "crew",
}
# Optical targets per family. high: equal visual mass (sqrt of coverage). royal: equal letter height.
# special / crew: full-bleed designs, only kept inside a 2 % safe margin. MAX: largest body extent allowed.
TARGET_MASS_HIGH = 0.76
TARGET_ROYAL_H = 0.80
MAX_EXTENT = 0.97


def measure(name):
    im = Image.open(os.path.join(GG, f"SYM-{name}.webp")).convert("RGBA")
    a = np.asarray(im).astype(np.float32) / 255
    A = a[..., 3]
    H, W = A.shape
    solid = (A > 0.5).astype(np.uint8) * 255
    body = np.asarray(Image.fromarray(solid).filter(ImageFilter.MinFilter(9))) > 0
    body = np.asarray(Image.fromarray(body.astype(np.uint8) * 255).filter(ImageFilter.MaxFilter(9))) > 0
    ys, xs = np.nonzero(body)
    x0, x1, y0, y1 = xs.min() / W, (xs.max() + 1) / W, ys.min() / H, (ys.max() + 1) / H
    rgb = a[..., :3]
    lum = 0.2126 * rgb[..., 0] + 0.7152 * rgb[..., 1] + 0.0722 * rgb[..., 2]
    thr = np.percentile(lum[body], 98.5)
    hy, hx = np.nonzero(body & (lum >= thr))
    cov = float(body.mean())
    fam = FAMILY[name]
    bw, bh = x1 - x0, y1 - y0
    if fam == "high":
        s = TARGET_MASS_HIGH / np.sqrt(cov)
    elif fam == "royal":
        s = TARGET_ROYAL_H / bh
    else:
        s = 1.0
    s = float(min(s, MAX_EXTENT / max(bw, bh)))
    # centre the body in the cell (the cell centre is the sprite anchor)
    dx = float(0.5 - (x0 + x1) / 2) * s
    dy = float(0.5 - (y0 + y1) / 2) * s
    return {
        "family": fam,
        "body": [round(x0, 4), round(y0, 4), round(x1, 4), round(y1, 4)],
        "coverage": round(cov, 4),
        "glint": [round(float(hx.mean() / W), 4), round(float(hy.mean() / H), 4)],
        "clipped": round(float((rgb[body].max(-1) > 0.985).mean()), 4),
        "fit": {"scale": round(s, 4), "dx": round(dx, 4), "dy": round(dy, 4)},
    }


def main():
    data = {n: measure(n) for n in FAMILY}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// GENERATED by art/measure_symbols.py from static/assets/gg/SYM-*.webp. Do not edit by hand.\n")
        f.write("export type SymbolMetrics = {\n\tfamily: 'high' | 'royal' | 'special' | 'crew';\n")
        f.write("\tbody: [number, number, number, number];\n\tcoverage: number;\n\tglint: [number, number];\n")
        f.write("\tclipped: number;\n\tfit: { scale: number; dx: number; dy: number };\n};\n\n")
        f.write("export const SYMBOL_METRICS: Record<string, SymbolMetrics> = ")
        f.write(json.dumps(data, indent="\t"))
        f.write(";\n")
    for n, d in data.items():
        print(n, d["family"], "fit", d["fit"], "body", d["body"], "glint", d["glint"], "clipped", d["clipped"])


if __name__ == "__main__":
    main()
