"""
Turn the SYM-FX-* cell-effect clips (short transparent VP9 clips that play over board cells) into sprite
sheets. A sheet animation starts on the frame it is asked for, needs no video decoder and costs almost
nothing to draw, so the crew "hits" on the board (wild stamp, clone, upgrade, vault reveal, crew exit) land
exactly with the symbol change, also on phones.

    python3 art/make_cellfx_sheets.py

Reads art/animations/SYM-FX-*.webm, writes frontend/getaway_gang/static/assets/fx/<id>.webp and
src/game/cellFxSheets.ts (frame layout and URLs).
"""
from __future__ import annotations

import glob
import json
import os
import subprocess
import tempfile

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'art', 'animations')
OUT = os.path.join(ROOT, 'frontend', 'getaway_gang', 'static', 'assets', 'fx')
TS = os.path.join(ROOT, 'frontend', 'getaway_gang', 'src', 'game', 'cellFxSheets.ts')
FRAME = 256   # px per frame (cells show at about 110-230 px)
COLS = 5
FPS = 30

os.makedirs(OUT, exist_ok=True)
meta = {}
for path in sorted(glob.glob(os.path.join(SRC, 'SYM-FX-*.webm'))):
    cid = os.path.basename(path)[:-5]
    with tempfile.TemporaryDirectory(dir='/dev/shm' if os.path.isdir('/dev/shm') else None) as tmp:
        # libvpx-vp9 decoder keeps the alpha channel
        subprocess.run(['ffmpeg', '-v', 'error', '-c:v', 'libvpx-vp9', '-i', path, '-vf', f'scale={FRAME}:{FRAME}:flags=lanczos',
                        '-pix_fmt', 'rgba', os.path.join(tmp, 'f%03d.png')], check=True)
        frames = sorted(glob.glob(os.path.join(tmp, 'f*.png')))
        n = len(frames)
        rows = (n + COLS - 1) // COLS
        sheet = Image.new('RGBA', (COLS * FRAME, rows * FRAME), (0, 0, 0, 0))
        for i, f in enumerate(frames):
            sheet.paste(Image.open(f).convert('RGBA'), ((i % COLS) * FRAME, (i // COLS) * FRAME))
    dst = os.path.join(OUT, f'{cid}.webp')
    sheet.save(dst, 'WEBP', quality=86, method=6)
    meta[cid] = {'frames': n, 'cols': COLS, 'size': FRAME}
    print(f'{cid}: {n} frames -> {os.path.getsize(dst) // 1024} KB')

lines = [
    '// Generated by art/make_cellfx_sheets.py: sprite sheets for the SYM-FX cell effects (frame layout + URL).',
    f'export const CELL_FX_FPS = {FPS};',
    'export const CELL_FX_SHEETS: Record<string, { url: string; frames: number; cols: number; size: number }> = {',
]
for cid, v in meta.items():
    lines.append(f"\t'{cid}': {{ url: new URL('../../assets/fx/{cid}.webp', import.meta.url).href, frames: {v['frames']}, cols: {v['cols']}, size: {v['size']} }},")
lines.append('};')
open(TS, 'w').write('\n'.join(lines) + '\n')
print('->', TS)
