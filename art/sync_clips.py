"""Copy rendered clips (art/animations/*.webm) into the game and write src/game/clipUrls.ts.
Run: python3 art/sync_clips.py"""
import os
import shutil
import subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "art", "animations")
DST = os.path.join(ROOT, "frontend", "getaway_gang", "static", "assets", "clips")
TS = os.path.join(ROOT, "frontend", "getaway_gang", "src", "game", "clipUrls.ts")

# rendered but not used by the game (the Buy Bonus button uses its delivered still states)
SKIP = {"UI-BUY-BONUS-ANIM", "WIN-BIG", "WIN-SUPER", "WIN-MEGA", "WIN-EPIC"}  # big wins are live (BigWinScene)
# bonus entry: the layered ENTRY-<BONUS>[-LOOP][-PORTRAIT] clips replace the 7 s story intros and their loops
SKIP |= {f"SCR-{b}-INTRO{s}" for b in ("HEIST", "ESCAPE", "HIDDEN") for s in ("", "-LOOP")}
def is_char_clip(i):
    """ANIM-<CREW>-<ACTION> character videos: the crew are animated live now (LivePose); -ABILITY-FX stays."""
    return i.startswith("ANIM-") and not i.endswith("-FX")


os.makedirs(DST, exist_ok=True)
for f in os.listdir(DST):  # remove clips that are no longer shipped
    if (f.startswith("SYM-") and "-ANIM-" in f) or f[:-5] in SKIP or is_char_clip(f[:-5]):
        os.remove(os.path.join(DST, f))
# symbol land/win animations are drawn live in the game (SymbolArt.svelte), not played from video
ids = sorted(f[:-5] for f in os.listdir(SRC) if f.endswith(".webm") and f[:-5] not in SKIP
             and not (f.startswith("SYM-") and "-ANIM-" in f) and not is_char_clip(f[:-5]))
for i in ids:
    shutil.copy2(os.path.join(SRC, i + ".webm"), os.path.join(DST, i + ".webm"))
def has_alpha(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "stream_tags=alpha_mode", "-of", "csv=p=0", path],
                         capture_output=True, text=True).stdout.strip()
    return out == "1"


opaque = [i for i in ids if not has_alpha(os.path.join(SRC, i + ".webm"))]
lines = ["// GENERATED by art/sync_clips.py -- animation clips rendered by video/ (Remotion).",
         "export const CLIP_URLS: Record<string, string> = {"]
lines += [f"\t'{i}': new URL('../../assets/clips/{i}.webm', import.meta.url).href," for i in ids]
lines += ["};", "/** Clips without an alpha channel: these also play where transparent WebM is unsupported (Safari). */",
          "export const OPAQUE_CLIPS = new Set<string>([" + ", ".join(f"'{i}'" for i in opaque) + "]);", ""]
open(TS, "w", encoding="UTF-8").write("\n".join(lines))
print(f"{len(ids)} clips ({len(opaque)} opaque) -> {DST}")
