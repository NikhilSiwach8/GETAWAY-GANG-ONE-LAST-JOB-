"""Generate frontend/getaway_gang/src/game/config.ts from the math game config (single source of truth).

Run: vendor/math-sdk/env/bin/python -I frontend/tools/gen_config.py
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path[:0] = [os.path.join(ROOT, "math", "games", "getaway_gang"), os.path.join(ROOT, "vendor", "math-sdk")]
os.chdir(os.path.join(ROOT, "vendor", "math-sdk"))
import game_config as gc  # noqa: E402
from game_config import GameConfig, PAYING  # noqa: E402

c = GameConfig()
symbols = {}
for s in PAYING:
    symbols[s] = {"paytable": [{str(k): c.paytable[(k, s)]} for k in (6, 5, 4, 3)]}
for prop, names in c.special_symbols.items():
    for n in names:
        symbols.setdefault(n, {"paytable": None, "special_properties": []})["special_properties"].append(prop)
_ante_path = os.path.join(os.path.dirname(gc.__file__), "library", "lut_weighting_ante.json")
_ante = json.load(open(_ante_path)) if os.path.exists(_ante_path) else {}
cfg = {
    "providerName": "getaway_gang_studio",
    "gameName": "getaway_gang",
    "gameID": c.game_id,
    "rtp": c.rtp,
    "numReels": c.num_reels,
    "numRows": c.num_rows,
    "wincap": c.wincap,
    "betModes": {
        bm.get_name(): {"cost": bm.get_cost(), "feature": bm.get_feature(), "buyBonus": bm.get_buybonus(), "rtp": bm.get_rtp(), "max_win": bm.get_wincap()}
        for bm in c.bet_modes
    },
    "symbols": symbols,
    "paddingReels": {"basegame": "", "freegame": ""},
    "features": {
        "anteCost": gc.ANTE_COST,
        "anteBonusFactor": gc.ANTE_BONUS_FACTOR,
        "anteBonusOneIn": round(_ante.get("bonus_one_in", 0), 1),
        "baseBonusOneIn": round(_ante.get("base_bonus_one_in", 0), 1),
        "meterThresholds": gc.METER_THRESHOLDS,
        "lootThresholds": [t for t, _ in gc.LOOT_MILESTONES],
        "maxRespinsPerChain": gc.MAX_RESPINS_PER_CHAIN,
        "escapeLevelUpAt": gc.ESCAPE_LEVEL_UP_AT,
        "heistMaxFs": gc.HEIST_MAX_FS,
        "escapeMaxFs": gc.ESCAPE_MAX_FS,
        "heistFs": c.freespin_triggers[c.basegame_type][3],
        "escapeFs": c.freespin_triggers[c.basegame_type][4],
        "retriggerFs": c.freespin_triggers[c.freegame_type][3],
        "finalEscapePerMaster": gc.FINAL_ESCAPE_PER_MASTER,
        "finalEscapeAllMasters": gc.FINAL_ESCAPE_ALL_MASTERS,
        "pbpMultiplier": gc.PBP_MULTIPLIER,
        "mysterySplit": gc.MYSTERY_SPLIT,
        "hiddenFs": gc.HIDDEN_FS,
        "hiddenStartLevel": gc.HIDDEN_START_LEVEL,
        "hiddenFloor": gc.HIDDEN_FLOOR,
    },
}
out = os.path.join(ROOT, "frontend", "getaway_gang", "src", "game", "config.ts")
with open(out, "w", encoding="UTF-8") as f:
    f.write("// GENERATED by frontend/tools/gen_config.py from math/games/getaway_gang/game_config.py -- do not edit.\n")
    f.write("export default " + json.dumps(cfg, indent="\t") + " as const;\n")
print("wrote", out)
