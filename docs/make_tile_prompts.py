"""Write docs/ASSET_PROMPTS_GAME_TILES.txt: lobby game tiles (3:4 portrait and 16:9 landscape), no text.
Style blocks come from docs/ASSET_PROMPTS.txt; the crew lock from the round-2 fixes.
Run: python3 docs/make_tile_prompts.py"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MASTER = open(os.path.join(HERE, "ASSET_PROMPTS.txt"), encoding="UTF-8").read()
FIXES = open(os.path.join(HERE, "make_round2_fix_prompts.py"), encoding="UTF-8").read()
GAME = 'the original online video slot game "GETAWAY GANG: ONE LAST JOB!" (an action-comedy heist slot)'
STYLE_3D = re.search(r"(Art style: premium stylized 3D.*?) Colour palette:", MASTER).group(1)
PALETTE = re.search(r"(Colour palette: .*?) Deliverable:", MASTER).group(1)
AVOID = re.search(r"(Avoid: .*?)\n", MASTER).group(1)
CREW_LOCK = "".join(re.findall(r'"(.*?)"', re.search(r'CREW_LOCK = \(\n(.*?)\n\)', FIXES, re.S).group(1)))

NO_TEXT = ("ABSOLUTELY NO TEXT anywhere: no title, no logo, no letters, numbers, signs, labels, watermarks or "
           "lettering on the van, banners, screens or money (the lobby adds the game name itself).")
CENTRE = ("Composition: everything important sits in the centre safe zone (the middle 70% of the width and height); "
          "faces, the van and the vault must never touch or be cut by the edges, because lobbies crop and round the "
          "corners of tiles differently. The outer 15% on every side is only background that can be cropped away.")
SCENE = ("The four crew burst out of a blown-open, glowing golden bank vault in a cloud of gold coins, banknotes and "
         "sparkling gems, mid-getaway, all grinning: Roxy at the front behind the steering wheel of the red getaway van, "
         "Tank hauling a giant overflowing money bag over his shoulder, Byte with his green holographic laptop, Fuse "
         "tossing a fizzing cartoon bomb with a wink. Warm molten-gold light from the vault behind them, cool navy night "
         "around the edges, strong rim light separating the characters from the background, high contrast and readable "
         "even as a small thumbnail.")
DELIV = "Deliverable: full-bleed PNG/WebP (no transparency), high-res, plus a layered source file."
TILES = [
    ("GAME-TILE-3x4", "Lobby game tile — portrait 3:4", "1200×1600 px (3:4 portrait, also used at 600×800)",
     "Portrait framing: the crew are stacked vertically in a tight, centred pyramid — Tank and his money bag at the top "
     "centre, Byte and Fuse to either side just below, Roxy and the front of the van at the bottom centre coming straight "
     "at the viewer; the open vault door is a glowing gold halo directly behind the group's centre."),
    ("GAME-TILE-16x9", "Lobby game tile — landscape 16:9", "1920×1080 px (16:9 landscape, also used at 960×540)",
     "Landscape framing: the red getaway van drives straight at the viewer, centred, with Roxy at the wheel; Tank and Byte "
     "lean out on the left side, Fuse on the right, all inside the middle 70%; the round open vault door glows like a gold "
     "sun directly behind the van, with coins and banknotes streaming outwards symmetrically to both sides."),
]


def prompt(name, size, framing):
    return " ".join([f'Create the asset "{name}" for {GAME}.', SCENE, framing, CENTRE, NO_TEXT, CREW_LOCK,
                     f"Size: {size}.", STYLE_3D, PALETTE, DELIV, AVOID,
                     "Also avoid: any text or logo, swapping the characters' genders, hair or outfits, important "
                     "details near the edges."])


out = ["GETAWAY GANG: ONE LAST JOB! -- LOBBY GAME TILES (no text, main content centred)",
       "Generated by docs/make_tile_prompts.py. Deliver files named exactly as the ids below.", ""]
for id_, name, size, framing in TILES:
    out += [f"=== {id_} — {name} ===", prompt(name, size, framing), ""]
open(os.path.join(HERE, "ASSET_PROMPTS_GAME_TILES.txt"), "w", encoding="UTF-8").write("\n".join(out))
print("\n".join(out))
