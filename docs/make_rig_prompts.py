"""Write docs/ASSET_PROMPTS_CHARACTER_RIG.txt: layered "cut-out" part sheets of the four crew, so they can be
rigged and animated (blinks, talking, arm and prop moves, breathing) instead of moving as one flat picture.
Style blocks come from docs/ASSET_PROMPTS.txt; each character's look from the round-2 CREW_LOCK.
Run: python3 docs/make_rig_prompts.py"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MASTER = open(os.path.join(HERE, "ASSET_PROMPTS.txt"), encoding="UTF-8").read()
FIXES = open(os.path.join(HERE, "make_round2_fix_prompts.py"), encoding="UTF-8").read()
GAME = 'the original online video slot game "GETAWAY GANG: ONE LAST JOB!" (an action-comedy heist slot)'
STYLE_3D = re.search(r"(Art style: premium stylized 3D.*?) Colour palette:", MASTER).group(1)
PALETTE = re.search(r"(Colour palette: .*?) Deliverable:", MASTER).group(1)
LOCK = "".join(re.findall(r'"(.*?)"', re.search(r'CREW_LOCK = \(\n(.*?)\n\)', FIXES, re.S).group(1)))
LOOK = {n: re.search(rf"({n} is .*?)(?= (?:ROXY|BYTE|TANK|FUSE) is | Each character keeps|$)", LOCK).group(1).strip()
        for n in ("ROXY", "BYTE", "TANK", "FUSE")}

CREW = {
    "ROXY": ("the getaway driver", "her red-and-white steering wheel", "her long auburn ponytail (2 pieces: base and tip, so it can swing)",
             "confident smirk"),
    "BYTE": ("the hacker", "his glowing green holographic laptop (and its hologram screen as a separate glow layer)", "his curly hair (1 piece)",
             "excited grin"),
    "TANK": ("the muscle", "his yellow-and-black industrial drill (drill bit as a separate piece so it can spin)", "his red bandana knot tails (1 piece)",
             "big toothy laugh"),
    "FUSE": ("the explosives expert", "her plunger detonator box (plunger handle as a separate piece) and one cartoon round bomb with a lit fuse",
             "her messy black-and-blue hair (2 pieces: back hair and front fringe)", "mischievous wink-grin"),
}

RIG = ("RIGGING SHEET FORMAT: one front-facing, neutral 'A-pose' (arms slightly away from the body, legs straight, weight even), "
       "the SAME scale and lighting as the full character. Every body part drawn COMPLETE and SEPARATE on a transparent background, "
       "laid out in a tidy grid with clear empty space between parts (no part touching or overlapping another). Each joint end is "
       "drawn with extra overlap (a rounded, fully painted end that would normally be hidden inside the neighbouring part), so the "
       "parts can rotate at the joints without gaps. Nothing is cropped at the canvas edge.")
NO_TEXT = "No text, labels, numbers, arrows or guide lines anywhere on the sheet."


def parts(name, prop, hair, mood):
    return (f"PARTS ({name}): 1) head without eyes, eyebrows, mouth or hair-front (bare face, so features are swapped on top); "
            f"2) {hair}; 3) eyes, 3 states side by side: open, half-closed, closed (blink), plus the pupils/irises as separate small pieces; "
            f"4) eyebrows, 2 states: neutral and raised; 5) mouths, 5 states: closed smile, {mood}, open 'O' (shout/surprise), "
            "wide 'A' (cheer), small 'M/B'; 6) neck; 7) torso with jacket/top (no arms); 8) pelvis/hips with belt; "
            "9) LEFT upper arm, LEFT forearm, LEFT hand open, LEFT hand fist / gripping; 10) the same four for the RIGHT arm; "
            "11) LEFT thigh, LEFT shin, LEFT boot; 12) the same three for the RIGHT leg; "
            f"13) the prop: {prop}; 14) any loose accessory (straps, cables, belt pouches, goggles) as its own piece; "
            "15) a soft contact shadow ellipse.")


def prompt(name):
    role, prop, hair, mood = CREW[name]
    return " ".join([
        f'Create the asset "{name} — rigging part sheet" for {GAME}: {name.title()}, {role}, split into separate layers for cut-out '
        "(Spine / 2D skeletal) animation, so the character can blink, talk, breathe, swing the arms and use the prop.",
        LOOK[name].rstrip(".") + ".",
        "Must match the existing character art exactly (attach CHR-" + name + "-POSE as reference if your tool allows).",
        RIG, parts(name, prop, hair, mood), NO_TEXT,
        "Size: 4096×4096 px canvas.", STYLE_3D, PALETTE,
        "Deliverable: PNG with a real transparent background (no white box, no checkerboard); if your tool supports it, also a layered "
        "PSD with every part on its own named layer (e.g. 'arm_upper_L').",
        "Avoid: a merged full-body picture, overlapping or touching parts, parts cut off by the edge, different lighting or scale between "
        "parts, changing the character's gender, hair, outfit or colours, text, watermarks.",
    ])


out = ["GETAWAY GANG: ONE LAST JOB! -- CHARACTER RIGGING PART SHEETS (for real character animation)",
       "Generated by docs/make_rig_prompts.py. Deliver files named exactly as the ids below (RIG-<NAME>.png / .psd).",
       "Tip: if a tool returns parts merged together, generate in two halves (head + face states / body + limbs + prop) with the "
       "same prompt and 'only the head parts' or 'only the body parts' added at the end.", ""]
for n in CREW:
    out += [f"=== RIG-{n} ===", prompt(n), ""]
open(os.path.join(HERE, "ASSET_PROMPTS_CHARACTER_RIG.txt"), "w", encoding="UTF-8").write("\n".join(out))
print("\n".join(out))
